#!/usr/bin/env node
/**
 * Slice the legacy CHAT reducer out of ChatDrawer.jsx so it can be RUN.
 *
 * Sibling of extract-jsx-reducer.mjs, which does the same for the GENERATION
 * reducer, and it exists for the same reason: `handleAskSocketMessage` is a
 * `useCallback` inside a 2,560-line component, closing over six setState calls,
 * four refs and a persistence helper, and it has no tests of any kind. To
 * characterise it you have to run it; to run it you have to get it out of the
 * component.
 *
 * The body is SLICED, verbatim, by line range. Retyping it into a harness would
 * produce a second implementation, and a differential against a copy proves
 * nothing about the code that ships.
 *
 * Run it, then record-chat.mjs, to regenerate __fixtures__/chat-oracle.json:
 *
 *   node scripts/deepwiki-oracle/extract-chat-reducer.mjs
 *   node scripts/deepwiki-oracle/record-chat.mjs > \
 *     src/features/wiki-chat/model/__fixtures__/chat-oracle.json
 *
 * The line range is asserted, not trusted: if the surrounding file moves, the
 * script fails loudly rather than slicing the wrong function.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
// The vendored bundle was deleted at the end of the port (P2.P9); its source
// is read from the commit pinned in parity/deepwiki-ui.pin, which is the last
// one that carried it. The line anchors below refer to that commit.
const PIN = readFileSync(resolve(here, '../../parity/deepwiki-ui.pin'), 'utf8').trim().split('\n')[0];
const SOURCE = `${PIN}:apps/deepwiki-ui/src/components/ChatDrawer.jsx`;
const FIRST_LINE = 1229; // `const handleAskSocketMessage = useCallback((data) => {`
const LAST_LINE = 1565; // `}, []);`

const lines = execFileSync('git', ['show', SOURCE], { encoding: 'utf8', cwd: resolve(here, '../../../..') }).split('\n');
const body = lines.slice(FIRST_LINE - 1, LAST_LINE).join('\n');

// The guards. A silently wrong slice is a harness that characterises the wrong
// function and an oracle that certifies the wrong behaviour.
if (!body.startsWith('  const handleAskSocketMessage = useCallback((data) => {')) {
  throw new Error(
    `line ${FIRST_LINE} is not the start of handleAskSocketMessage; the source has moved`,
  );
}
// The EMPTY dependency array is load-bearing, not incidental. Every value the
// body reads is a ref, a setState identity, or a module constant, so nothing it
// closes over changes between renders — which is what makes the stub closure
// below a complete substitute. A callback that had grown a dependency would
// read something the stub does not supply, and this check fails on it.
if (!body.trimEnd().endsWith('}, []);')) {
  throw new Error(
    `line ${LAST_LINE} is not the end of the callback, or it grew a dependency; the source has moved`,
  );
}

writeFileSync(
  resolve(here, 'chatReducer.generated.mjs'),
  `// GENERATED by extract-chat-reducer.mjs — do not edit.
// Sliced verbatim from apps/deepwiki-ui/src/components/ChatDrawer.jsx:${FIRST_LINE}-${LAST_LINE}.
export function makeJsxChatReducer(deps) {
  const {
    setMessages, setResearchTodos, setPendingAnswer, setError, setIsLoading,
    setChatMode, persistLastCapability, SocketMessageType,
    MAX_THINKING_STEPS_PER_RUN,
    currentStreamIdRef, currentMessageIdRef, currentThinkingBlockIdRef,
    pendingCapabilityRef, socketUnsubscribeRef,
  } = deps;
  const useCallback = (fn) => fn;
${body}
  return handleAskSocketMessage;
}
`,
);
process.stdout.write(`sliced ${String(LAST_LINE - FIRST_LINE + 1)} lines into chatReducer.generated.mjs\n`);
