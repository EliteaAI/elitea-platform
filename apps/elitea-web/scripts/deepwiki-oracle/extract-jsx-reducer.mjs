#!/usr/bin/env node
/**
 * Slice the legacy generation reducer out of the JSX so it can be RUN.
 *
 * WHY THIS SCRIPT EXISTS RATHER THAN A COPY. The reducer is a `useCallback`
 * inside a 5,107-line component, closing over two setState calls and eight
 * refs, and it had no tests of any kind. To characterise it you have to run it;
 * to run it you have to get it out of the component. Retyping it into a harness
 * would produce a second implementation, and a differential against a copy
 * proves nothing about the code that ships — which is exactly the trap
 * getConfiguredRepo.test.js fell into (823 lines testing inline copies).
 *
 * So the body is SLICED, verbatim, by line range, and the only thing added is a
 * wrapper that supplies the closure.
 *
 * Run it, then record.mjs, to regenerate __fixtures__/generation-oracle.json:
 *
 *   node scripts/deepwiki-oracle/extract-jsx-reducer.mjs
 *   node scripts/deepwiki-oracle/record.mjs > \
 *     src/features/wiki-generation/lib/__fixtures__/generation-oracle.json
 *
 * The line range is asserted, not trusted: if the surrounding file moves, the
 * script fails loudly rather than slicing the wrong function.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
// The vendored bundle was deleted at the end of the port (P2.P9); its source
// is read from the commit pinned in parity/deepwiki-ui.pin, which is the last
// one that carried it. The line anchors below refer to that commit.
const PIN = readFileSync(resolve(here, '../../parity/deepwiki-ui.pin'), 'utf8').trim().split('\n')[0];
const SOURCE = `${PIN}:apps/deepwiki-ui/src/DeepWikiApp.jsx`;
const FIRST_LINE = 1680; // `const handleWikiSocketMessage = useCallback(...`
const LAST_LINE = 1924; // `}, [toolkit, cleanupGeneration]);`

const lines = execFileSync('git', ['show', SOURCE], { encoding: 'utf8', cwd: resolve(here, '../../../..') }).split('\n');
const body = lines.slice(FIRST_LINE - 1, LAST_LINE).join('\n');

// The guards. A silently wrong slice is a harness that characterises the wrong
// function and an oracle that certifies the wrong behaviour.
if (!body.startsWith('  const handleWikiSocketMessage = useCallback(')) {
  throw new Error(
    `line ${FIRST_LINE} is not the start of handleWikiSocketMessage; the source has moved`,
  );
}
if (!body.trimEnd().endsWith('}, [toolkit, cleanupGeneration]);')) {
  throw new Error(`line ${LAST_LINE} is not the end of the callback; the source has moved`);
}

writeFileSync(
  resolve(here, 'jsxReducer.generated.mjs'),
  `// GENERATED by extract-jsx-reducer.mjs — do not edit.
// Sliced verbatim from apps/deepwiki-ui/src/DeepWikiApp.jsx:${FIRST_LINE}-${LAST_LINE}.
export function makeJsxReducer(deps) {
  const {
    setGenerationStatus, setThinkingSteps, cleanupGeneration, getBucketName,
    loadArtifactsList, updateGenerationState, SocketMessageType,
    projectId, toolkitId, toolkit, configuredRepoIdentity,
    currentStreamIdRef, currentTaskIdRef, generationErroredRef, isReconnectingRef,
    lastSocketEventTimeRef, reconnectTimeoutRef, socketUnsubscribeRef, stepIdCounterRef,
  } = deps;
  const useCallback = (fn) => fn;
${body}
  return handleWikiSocketMessage;
}
`,
);
process.stdout.write(`sliced ${String(LAST_LINE - FIRST_LINE + 1)} lines into jsxReducer.generated.mjs\n`);
